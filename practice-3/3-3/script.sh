#!/bin/bash

echo "Начинаем сборку Задания 3-3 (Вариант 7)..."

# Компиляция C-файла
gcc -Wall -Wextra -o task task.c

# Проверка, успешно ли прошла компиляция
if [ $? -eq 0 ]; then
    echo "Компиляция успешна! Запускаем программу..."
    echo "----------------------------------------"
    ./task
    echo "----------------------------------------"
    echo "Программа завершила работу."
else
    echo "Ошибка компиляции! Проверьте исходный код."
    exit 1
fi